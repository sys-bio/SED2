# Phase-1 test-specsheets/ vocabulary exercised; the real spec (specsheets/)
# also uses the other four. Every one of these gets the same six get-/set-/
# is-Ref-/isSet-/unset- accessors, generic OrRef storage (get_or_ref_value_
# node/set_or_ref_value_node/... on SedBase), differing only in the natural
# C++ type on the value side - ArrayOrRef/DictOrRef have no better native
# C++ collection representation than the raw Json itself without
# a lot more work outside this port's scope (Design.md's Phase 2 scope
# note), so their "value" is the json as-is, same treatment as "any" below.
_ORREF_KINDS_CPP = ("StringOrRef", "NumberOrRef", "IntegerOrRef", "BooleanOrRef", "ArrayOrRef", "DictOrRef")

# kind -> (C++ value type, get-conversion suffix ("" = no conversion, the
# Json itself), param type for the setter, set-time wrap
# expression turning `value` into a Json).
_ORREF_CPP_TYPES = {
    "StringOrRef": ("std::string", ".as<std::string>()", "const std::string&", "Json(value)"),
    "NumberOrRef": ("double", ".as<double>()", "double", "Json(value)"),
    "IntegerOrRef": ("int64_t", ".as<int64_t>()", "int64_t", "Json(value)"),
    "BooleanOrRef": ("bool", ".as<bool>()", "bool", "Json(value)"),
    "ArrayOrRef": ("Json", "", "const Json&", "value"),
    "DictOrRef": ("Json", "", "const Json&", "value"),
}

# Every kind emit_model_hpp treats as a "leaf" field (own FIELD_SPECS entry
# + a get-/set-/isSet-/unset()-shaped accessor stored directly in values_) -
# mirrors emit_python.py's emit_model_py leaf_fields classification
# (_ORREF_KINDS + ("string", "integer", ... , "any")).
_LEAF_KINDS_CPP = _ORREF_KINDS_CPP + ("string", "integer", "number", "boolean", "SId", "SIdRef", "any")


def _cpp_leaf_type(kind: str) -> str:
    return {"string": "std::string", "SId": "std::string", "SIdRef": "std::string",
            "integer": "int64_t", "number": "double", "boolean": "bool"}[kind]


def _leaf_accessors_cpp(f: Field) -> str:
    ident = _cpp_ident(f.name)
    kind = f.type.kind
    name_lit = _cpp_lit(f.name)
    lines = []
    if f.is_math and kind in _ORREF_KINDS_CPP:
        # A math string is always an expression, never a reference to a
        # string (Calculation description), even when it starts with '#': so
        # there is only a value accessor, which returns the text as it is.
        cpp_t, get_expr, param_t, wrap = _ORREF_CPP_TYPES[kind]
        lines.append(f"    {cpp_t} get_{ident}_value() const {{ auto it = values_.find({name_lit}); "
                      f"if (it == values_.end()) throw ApiError(std::string({name_lit}) + \" is not set\"); "
                      f"return it->second{get_expr}; }}")
        lines.append(f"    void set_{ident}_value({param_t} value) {{ values_[{name_lit}] = {wrap}; or_ref_is_ref_.erase({name_lit}); }}")
        lines.append(f"    bool is_set_{ident}() const {{ return values_.count({name_lit}) > 0; }}")
        lines.append(f"    void unset_{ident}() {{ values_.erase({name_lit}); or_ref_is_ref_.erase({name_lit}); }}")
    elif kind in _ORREF_KINDS_CPP:
        cpp_t, get_expr, param_t, wrap = _ORREF_CPP_TYPES[kind]
        lines.append(f"    {cpp_t} get_{ident}_value() const {{ return get_or_ref_value_node({name_lit}){get_expr}; }}")
        lines.append(f"    std::string get_{ident}_ref() const {{ return get_or_ref_ref_node({name_lit}).as<std::string>(); }}")
        lines.append(f"    void set_{ident}_value({param_t} value) {{ set_or_ref_value_node({name_lit}, {wrap}); }}")
        lines.append(f"    void set_{ident}_ref(const std::string& ref) {{ set_or_ref_ref_node({name_lit}, ref); }}")
        lines.append(f"    bool is_{ident}_ref() const {{ return is_or_ref_ref({name_lit}); }}")
        lines.append(f"    bool is_set_{ident}() const {{ return values_.count({name_lit}) > 0; }}")
        lines.append(f"    void unset_{ident}() {{ values_.erase({name_lit}); or_ref_is_ref_.erase({name_lit}); }}")
    elif kind == "any":
        # AnyValueOrRef: no fixed shape, so no type conversion either way -
        # the raw Json is both the getter's return type and the
        # setter's parameter type. Mirrors emit_python.py's plain (non-
        # OrRef) accessor shape for this kind - "any" is deliberately absent
        # from validate_own()'s leaf_kinds set (there is no leaf schema for
        # "any JSON value"), so the stored value is never schema-checked;
        # only a reference-valued one gets reference resolution, and a
        # missing one required-ness.
        lines.append(f"    Json get_{ident}() const {{ auto it = values_.find({name_lit}); "
                      f"if (it == values_.end()) throw ApiError(std::string({name_lit}) + \" is not set\"); "
                      f"return it->second; }}")
        lines.append(f"    void set_{ident}(const Json& value) {{ values_[{name_lit}] = value; }}")
        lines.append(f"    bool is_set_{ident}() const {{ return values_.count({name_lit}) > 0; }}")
        lines.append(f"    void unset_{ident}() {{ values_.erase({name_lit}); }}")
    else:
        cpp_t = _cpp_leaf_type(kind)
        param_t = "const std::string&" if cpp_t == "std::string" else cpp_t
        get_expr = f".as<{cpp_t}>()"
        lines.append(f"    {cpp_t} get_{ident}() const {{ auto it = values_.find({name_lit}); "
                      f"if (it == values_.end()) throw ApiError(std::string({name_lit}) + \" is not set\"); "
                      f"return it->second{get_expr}; }}")
        lines.append(f"    void set_{ident}({param_t} value) {{ values_[{name_lit}] = Json(value); }}")
        lines.append(f"    bool is_set_{ident}() const {{ return values_.count({name_lit}) > 0; }}")
        lines.append(f"    void unset_{ident}() {{ values_.erase({name_lit}); }}")
    return "\n".join(lines) + "\n"


def _child_accessors_cpp(f: Field) -> str:
    """A single nested SedBase-derived child, owned directly by the
    instance (a private std::unique_ptr<SedBase> field), not in an
    IdKeyedCollection/ListCollection - there is exactly zero or one of it,
    and it has no id of its own. Covers both "ref-class" (a fixed target
    class) and "ref-discriminator" (a _type-dispatched target) - the
    accessors don't care which; only load_fields()'s own parsing needs to
    tell them apart (see generator/emit_python.py's _child_accessors, the
    reference implementation this mirrors)."""
    ident = _cpp_ident(f.name)
    name_lit = _cpp_lit(f.name)
    lines = []
    lines.append(f"    SedBase* get_{ident}() const {{ if (!{ident}_) throw ApiError(std::string({name_lit}) + \" is not set\"); return {ident}_.get(); }}")
    lines.append(f"    void set_{ident}(std::unique_ptr<SedBase> obj) {{ SedBase* raw = obj.get(); {ident}_ = std::move(obj); raw->attach(this, get_document()); }}")
    lines.append(f"    bool is_set_{ident}() const {{ return {ident}_ != nullptr; }}")
    lines.append(f"    void unset_{ident}() {{ {ident}_.reset(); }}")
    return "\n".join(lines) + "\n"


def _collection_accessors_cpp(f: Field) -> str:
    ident = _cpp_ident(f.name)
    name_lit = _cpp_lit(f.name)
    lines = []
    if f.type.kind == "dict":
        lines.append(f"    std::vector<std::string> get_{ident}() const {{ return {ident}_.ids(); }}")
        lines.append(f"    SedBase* get_{ident}_item(const std::string& item_id) const {{ return {ident}_.get(item_id); }}")
        lines.append(f"    void add_{ident}(const std::string& item_id, std::unique_ptr<SedBase> obj) {{ "
                      f"SedBase* raw = obj.get(); {ident}_.add(item_id, std::move(obj)); raw->attach(this, get_document()); }}")
        lines.append(f"    void insert_{ident}(size_t index, const std::string& item_id, std::unique_ptr<SedBase> obj) {{ "
                      f"SedBase* raw = obj.get(); {ident}_.insert(index, item_id, std::move(obj)); raw->attach(this, get_document()); }}")
        lines.append(f"    void remove_{ident}(const std::string& item_id) {{ {ident}_.remove(item_id); }}")
        lines.append(f"    void set_id_on_{ident}(const std::string& old_id, const std::string& new_id) {{ {ident}_.set_id(old_id, new_id); }}")
    elif f.type.kind == "any-dict":
        # Same ID-keyed collection shape as "dict", but items are raw
        # Json values, never SedBase instances - so no attach()
        # call (SEDDocument.constants today; mirrors
        # generator/emit_python.py's _collection_accessors any-dict
        # branch).
        lines.append(f"    std::vector<std::string> get_{ident}() const {{ return {ident}_.ids(); }}")
        lines.append(f"    Json get_{ident}_item(const std::string& item_id) const {{ return {ident}_.get(item_id); }}")
        lines.append(f"    void add_{ident}(const std::string& item_id, const Json& value) {{ {ident}_.add(item_id, value); }}")
        lines.append(f"    void insert_{ident}(size_t index, const std::string& item_id, const Json& value) {{ {ident}_.insert(index, item_id, value); }}")
        lines.append(f"    void remove_{ident}(const std::string& item_id) {{ {ident}_.remove(item_id); }}")
        lines.append(f"    void set_id_on_{ident}(const std::string& old_id, const std::string& new_id) {{ {ident}_.set_id(old_id, new_id); }}")
    else:
        lines.append(f"    std::vector<SedBase*> get_{ident}() const {{ return {ident}_.items(); }}")
        lines.append(f"    void add_{ident}(std::unique_ptr<SedBase> obj) {{ "
                      f"SedBase* raw = obj.get(); {ident}_.add(std::move(obj)); raw->attach(this, get_document()); }}")
        lines.append(f"    void insert_{ident}(size_t index, std::unique_ptr<SedBase> obj) {{ "
                      f"SedBase* raw = obj.get(); {ident}_.insert(index, std::move(obj)); raw->attach(this, get_document()); }}")
        lines.append(f"    void remove_{ident}(size_t index) {{ {ident}_.remove(index); }}")
    return "\n".join(lines) + "\n"


def _collection_field_decl_cpp(f: Field) -> str:
    ident = _cpp_ident(f.name)
    if f.type.kind == "dict":
        cls = "IdKeyedCollection"
    elif f.type.kind == "any-dict":
        cls = "AnyDictCollection"
    else:
        cls = "ListCollection"
    return f"    {cls} {ident}_;\n"


def emit_model_hpp(model: SpecModel) -> str:
    base = model.base_mixin
    base_fields = model.classes[base].fields if base in model.classes else []
    base_name_rule_id = next((f.rule_id for f in base_fields if f.name == "name"), None)
    base_desc_rule_id = next((f.rule_id for f in base_fields if f.name == "description"), None)
    base_catchall = model.classes[base].own_catchall if base in model.classes else ""

    out = [f'''// Generated concrete SED2 classes. GENERATED - do not
// hand-edit; regenerate from {model.spec_root_label()}/ via generator/generate.py.
#pragma once

#include "Runtime.hpp"
// SedBase::validate_own() (Runtime.hpp) only *declares*
// MathRules::check_math_field() (to break a header cycle - see
// MathRules.hpp's docstring); this is the one place, upstream of every
// concrete class below and every consumer that includes this file, that
// pulls in its actual `inline` definition so the symbol is always
// available wherever validate_own() might be called.
#include "MathRules.hpp"
// Same pattern for the reference-driven rules: SedBase::validate_own() only
// declares class RefRules (Runtime.hpp); RefRules.hpp supplies the bodies
// (and, via Rules.hpp, the handwritten per-rule check() functions).
#include "RefRules.hpp"

#include <memory>
#include <string>
#include <vector>

namespace {NS} {{

''']

    for name in model.generatable_classes():
        c = model.classes[name]
        # Mirrors emit_python.py's own_fields filter exactly (and, since
        # this fix, emit_java.py's): excludes ONLY name/description when
        # they originate from the base mixin (every concrete class handles
        # those two via the dedicated name_node_/description_node_ fields
        # on SedBase itself, never a FieldSpec) - NOT every base-origin
        # field. The base mixin (SEDBase/TestBase) also declares "notes"/
        # "annotations" in the real spec (TestBase happens to declare only
        # name/description, which is why this distinction was invisible
        # under test-specsheets/ alone) and those must still get their own
        # FieldSpec/accessor like any other field.
        own_fields = [f for f in c.fields
                      if not (f.origin_class == base and f.name in ("name", "description"))]
        collection_fields_all = [f for f in own_fields if f.type.kind in ("dict", "array", "any-dict")]
        leaf_fields_all = [f for f in own_fields if f.type.kind in _LEAF_KINDS_CPP]
        child_fields_all = [f for f in own_fields if f.type.kind in ("ref-class", "ref-discriminator")]

        # A field name can legitimately appear twice in own_fields (a
        # subclass re-declaring a field its own mixin already declares with
        # a tighter constraint, e.g. NumericRange/ParameterRange's own
        # "values" alongside Range's mixin "values" - both keep their own
        # separate FieldSpec entry in field_specs below, matching
        # emit_python.py's _FIELDS, but C++ cannot declare the same member
        # (a field or a method) twice in one class, unlike Python where a
        # later `def`/assignment inside the class body silently shadows an
        # earlier one with the same name). Field DECLARATIONS and their
        # ACCESSOR METHODS are deduplicated (last occurrence wins, matching
        # Python's overwrite order and mirroring emit_java.py's own
        # _dedup_last); FIELD_SPECS below deliberately is NOT.
        def _dedup_last(fields):
            by_name = {}
            order = []
            for f in fields:
                if f.name not in by_name:
                    order.append(f.name)
                by_name[f.name] = f
            return [by_name[n] for n in order]

        collection_fields = _dedup_last(collection_fields_all)
        leaf_fields = _dedup_last(leaf_fields_all)
        child_fields = _dedup_last(child_fields_all)
        dict_fields = [f for f in collection_fields if f.type.kind == "dict"]
        array_fields = [f for f in collection_fields if f.type.kind == "array"]
        any_dict_fields = [f for f in collection_fields if f.type.kind == "any-dict"]
        has_ns = bool(c.namespace_updates)

        out.append(f"/// Generated from {model.spec_root_label()}/{c.category}/{name}/.\n")
        out.append(f"class {name} : public SedBase {{\npublic:\n")

        field_specs = leaf_fields_all + collection_fields_all + child_fields_all
        if field_specs:
            exprs = ",\n            ".join(_field_spec_expr(f) for f in field_specs)
            out.append(f"    const std::vector<FieldSpec>& field_specs() const override {{\n"
                        f"        static const std::vector<FieldSpec> specs = {{\n            {exprs}\n        }};\n"
                        f"        return specs;\n    }}\n")
        req_names = [f.name for f in own_fields if f.required]
        if req_names:
            names_lit = ", ".join(_cpp_lit(n) for n in req_names)
            out.append(f"    const std::set<std::string>& required_names() const override {{\n"
                        f"        static const std::set<std::string> names = {{{names_lit}}};\n        return names;\n    }}\n")

        out.append(f"    std::optional<std::string> type_const() const override {{ return {_cpp_opt_str(c.type_const)}; }}\n")
        out.append(f"    std::optional<std::string> type_rule_id() const override {{ return {_cpp_opt_str(c.type_rule_id)}; }}\n")
        out.append(f"    std::string own_catchall() const override {{ return {_cpp_lit(c.own_catchall)}; }}\n")
        out.append(f"    std::optional<std::string> name_rule_id() const override {{ return {_cpp_opt_str(base_name_rule_id)}; }}\n")
        out.append(f"    std::optional<std::string> desc_rule_id() const override {{ return {_cpp_opt_str(base_desc_rule_id)}; }}\n")
        out.append(f"    std::string base_catchall() const override {{ return {_cpp_lit(base_catchall)}; }}\n")
        out.append(f"    std::string class_name() const override {{ return {_cpp_lit(name)}; }}\n")
        # -- reference-resolution metadata (see SedBase's virtuals in Runtime.hpp;
        # mirrors emit_python.py's _get_id_collection/_id_collection_names/
        # _OUTPUTS_JSON/_IS_DOCUMENT_CLASS emission) --
        if dict_fields:
            out.append("    const IdKeyedCollection* find_dict_collection(const std::string& field_name) const override {\n")
            for f in dict_fields:
                out.append(f"        if (field_name == {_cpp_lit(f.name)}) return &{_cpp_ident(f.name)}_;\n")
            out.append("        return nullptr;\n    }\n")
        if any_dict_fields:
            out.append("    const AnyDictCollection* find_any_dict_collection(const std::string& field_name) const override {\n")
            for f in any_dict_fields:
                out.append(f"        if (field_name == {_cpp_lit(f.name)}) return &{_cpp_ident(f.name)}_;\n")
            out.append("        return nullptr;\n    }\n")
        id_coll_fields = [f for f in collection_fields if f.type.kind in ("dict", "any-dict")]
        if id_coll_fields:
            names_lit = ", ".join(_cpp_lit(f.name) for f in id_coll_fields)
            out.append(f"    std::vector<std::string> id_collection_names() const override {{ return {{{names_lit}}}; }}\n")
        if c.outputs_json is not None:
            out.append("    const Json* outputs_json() const override {\n"
                        "        static const Json j = Json::parse(\n"
                        + _cpp_chunked_lit(_outputs_json_text(c.outputs_json)) + ");\n"
                        "        return &j;\n    }\n")
        if c.is_document:
            out.append("    bool is_document_class() const override { return true; }\n")
            out.append(f"    std::optional<std::string> max_known_document_version() const override {{ return {_cpp_opt_str(model.document_version)}; }}\n")
        if c.type_const is not None:
            out.append(f"    std::optional<std::string> get_type_value() const override {{ return std::string({_cpp_lit(c.type_const)}); }}\n")
        if has_ns:
            ns_field_entries = []
            for prefix, fs in c.namespace_updates.items():
                exprs = ", ".join(_field_spec_expr(f) for f in fs)
                ns_field_entries.append(f"{{{_cpp_lit(prefix)}, {{{exprs}}}}}")
            out.append(f"    const std::map<std::string, std::vector<FieldSpec>>& namespace_fields() const override {{\n"
                        f"        static const std::map<std::string, std::vector<FieldSpec>> m = {{\n            "
                        + ",\n            ".join(ns_field_entries) + "\n        };\n        return m;\n    }\n")
            catchall_entries = ", ".join(f"{{{_cpp_lit(p)}, {_cpp_lit(cc)}}}" for p, cc in c.namespace_catchalls.items())
            out.append(f"    const std::map<std::string, std::string>& namespace_catchall() const override {{\n"
                        f"        static const std::map<std::string, std::string> m = {{{catchall_entries}}};\n"
                        f"        return m;\n    }}\n")
            known_prefixes = ", ".join(_cpp_lit(p) for p in c.namespace_updates)
            out.append(f"    const std::set<std::string>& known_namespace_prefixes() const override {{\n"
                        f"        static const std::set<std::string> s = {{{known_prefixes}}};\n"
                        f"        return s;\n    }}\n")
        if c.type_const is not None:
            out.append(f"    std::string get_type() const {{ return {_cpp_lit(c.type_const)}; }}\n")
        out.append("\n")

        for f in leaf_fields:
            out.append(_leaf_accessors_cpp(f) + "\n")
        for f in collection_fields:
            out.append(_collection_accessors_cpp(f) + "\n")
        for f in child_fields:
            out.append(_child_accessors_cpp(f) + "\n")
        for prefix, fs in c.namespace_updates.items():
            for f in fs:
                out.append(_leaf_accessors_cpp(f) + "\n")

        if collection_fields or child_fields:
            out.append("    std::vector<SedBase*> children() override {\n        std::vector<SedBase*> kids;\n")
            for f in dict_fields:
                ident = _cpp_ident(f.name)
                out.append(f"        for (const auto& i : {ident}_.ids()) kids.push_back({ident}_.get(i));\n")
            for f in array_fields:
                ident = _cpp_ident(f.name)
                out.append(f"        for (auto* item : {ident}_.items()) kids.push_back(item);\n")
            for f in child_fields:
                ident = _cpp_ident(f.name)
                out.append(f"        if ({ident}_) kids.push_back({ident}_.get());\n")
            out.append("        return kids;\n    }\n\n")

            out.append("    std::vector<ChildLoc> children_with_locations() override {\n        std::vector<ChildLoc> out;\n")
            for f in dict_fields:
                ident = _cpp_ident(f.name)
                out.append(f"        for (const auto& i : {ident}_.ids()) out.push_back(ChildLoc{{{ident}_.get(i), \"/{f.name}/\" + i}});\n")
            for f in array_fields:
                ident = _cpp_ident(f.name)
                out.append(f"        {{ size_t idx = 0; for (auto* item : {ident}_.items()) {{ "
                            f"out.push_back(ChildLoc{{item, \"/{f.name}/\" + std::to_string(idx)}}); idx++; }} }}\n")
            for f in child_fields:
                ident = _cpp_ident(f.name)
                out.append(f"        if ({ident}_) out.push_back(ChildLoc{{{ident}_.get(), \"/{f.name}\"}});\n")
            out.append("        return out;\n    }\n\n")

        if dict_fields:
            out.append("    IdKeyedCollection& get_dict_collection(const std::string& field_name) override {\n")
            for f in dict_fields:
                ident = _cpp_ident(f.name)
                out.append(f"        if (field_name == {_cpp_lit(f.name)}) return {ident}_;\n")
            out.append("        return SedBase::get_dict_collection(field_name);\n    }\n\n")
        if array_fields:
            out.append("    ListCollection& get_list_collection(const std::string& field_name) override {\n")
            for f in array_fields:
                ident = _cpp_ident(f.name)
                out.append(f"        if (field_name == {_cpp_lit(f.name)}) return {ident}_;\n")
            out.append("        return SedBase::get_list_collection(field_name);\n    }\n\n")
        if any_dict_fields:
            out.append("    AnyDictCollection& get_any_dict_collection(const std::string& field_name) override {\n")
            for f in any_dict_fields:
                ident = _cpp_ident(f.name)
                out.append(f"        if (field_name == {_cpp_lit(f.name)}) return {ident}_;\n")
            out.append("        return SedBase::get_any_dict_collection(field_name);\n    }\n\n")
        if child_fields:
            out.append("    void set_child_field(const std::string& field_name, std::unique_ptr<SedBase> child) override {\n")
            for f in child_fields:
                ident = _cpp_ident(f.name)
                out.append(f"        if (field_name == {_cpp_lit(f.name)}) {{ {ident}_ = std::move(child); return; }}\n")
            out.append("        SedBase::set_child_field(field_name, std::move(child));\n    }\n\n")

        out.append("    Json own_json_value() const override {\n        Json d = Json::object();\n")
        out.append("        if (name_node_) d[\"name\"] = *name_node_;\n")
        out.append("        if (description_node_) d[\"description\"] = *description_node_;\n")
        if c.type_const is not None:
            out.append(f"        d[\"_type\"] = values_.count(\"_type\") ? values_.at(\"_type\") : Json({_cpp_lit(c.type_const)});\n")
        for f in leaf_fields:
            out.append(f"        if (values_.count({_cpp_lit(f.name)})) d[{_cpp_lit(f.name)}] = values_.at({_cpp_lit(f.name)});\n")
        for prefix, fs in c.namespace_updates.items():
            for f in fs:
                out.append(f"        if (values_.count({_cpp_lit(f.name)})) d[{_cpp_lit(f.name)}] = values_.at({_cpp_lit(f.name)});\n")
        for f in dict_fields:
            ident = _cpp_ident(f.name)
            out.append(f"        if ({ident}_.size() > 0) {{ Json sub = Json::object(); "
                        f"for (const auto& i : {ident}_.ids()) sub[i] = {ident}_.get(i)->to_json_value(); d[{_cpp_lit(f.name)}] = sub; }}\n")
        for f in array_fields:
            ident = _cpp_ident(f.name)
            out.append(f"        if ({ident}_.size() > 0) {{ Json arr = Json::array(); "
                        f"for (auto* item : {ident}_.items()) arr.push_back(item->to_json_value()); d[{_cpp_lit(f.name)}] = arr; }}\n")
        for f in any_dict_fields:
            ident = _cpp_ident(f.name)
            out.append(f"        if ({ident}_.size() > 0) {{ Json sub = Json::object(); "
                        f"for (const auto& i : {ident}_.ids()) sub[i] = {ident}_.get(i); d[{_cpp_lit(f.name)}] = sub; }}\n")
        for f in child_fields:
            ident = _cpp_ident(f.name)
            out.append(f"        if ({ident}_) d[{_cpp_lit(f.name)}] = {ident}_->to_json_value();\n")
        out.append("        for (const auto& kv : ns_attrs_) d[kv.first] = kv.second;\n")
        out.append("        return d;\n    }\n")

        if collection_fields or child_fields:
            out.append("\nprivate:\n")
            for f in collection_fields:
                out.append(_collection_field_decl_cpp(f))
            for f in child_fields:
                ident = _cpp_ident(f.name)
                out.append(f"    std::unique_ptr<SedBase> {ident}_;\n")

        out.append("};\n\n")

    for disc_name, disc in model.discriminators.items():
        uname = disc.unknown_class_name
        out.append(f'''/// Opaque holder for a {disc_name} instance whose _type names an
/// unregistered namespace prefix (see Design.md's Namespaces section) -
/// round-trips unchanged, never itself a validation error.
class {uname} : public SedBase {{
public:
    {uname}(std::string type_value, Json raw)
        : type_value_(std::move(type_value)), raw_(std::move(raw)) {{}}

    std::string get_type() const {{ return type_value_; }}
    std::optional<std::string> get_type_value() const override {{
        if (!raw_.contains("_type") || !raw_.at("_type").is_string()) return std::nullopt;
        return type_value_;
    }}
    std::string class_name() const override {{ return {_cpp_lit(uname)}; }}

    Json own_json_value() const override {{
        Json d = raw_;
        if (name_node_) d["name"] = *name_node_;
        if (description_node_) d["description"] = *description_node_;
        return d;
    }}

    std::set<std::string> allowed_keys() const override {{
        std::set<std::string> keys;
        for (const auto& kv : raw_.object_range()) keys.insert(kv.key());
        return keys;
    }}

protected:
    std::vector<ValidationProblem> validate_own() override {{ return {{}}; }}

private:
    std::string type_value_;
    Json raw_;
}};

''')

    out.append(f"}}  // namespace {NS}\n")
    return "".join(out)


def emit_dispatch_hpp(model: SpecModel) -> str:
    out = [f'''// Generated dispatch/parse per discriminator, plus the generic field
// loader used by every parse_* function and by Io::read_from_string().
// All load-time violations (extra/unrecognized properties, bad
// dict-of-discriminated-union keys, bad container shapes, and dispatch
// problems bubbled up from a nested item) are appended straight onto
// obj->load_problems_ - this is the only point that sees the raw JSON
// before an unrecognized key is dropped, so it is the only reliable place
// to detect them (see Design.md's Schema-Pass Errors section - mirrors
// generator/emit_python.py's _load_fields()). GENERATED - do not
// hand-edit; regenerate from {model.spec_root_label()}/ via generator/generate.py.
#pragma once

#include "Runtime.hpp"
#include "GeneratedModel.hpp"

#include <memory>
#include <optional>
#include <regex>
#include <set>
#include <string>

namespace {NS} {{

struct DispatchResult {{
    std::unique_ptr<SedBase> value;
    std::optional<ValidationProblem> problem;
}};

inline void load_fields(SedBase* obj, const Json& raw);

''']

    for disc_name, disc in model.discriminators.items():
        uname = disc.unknown_class_name
        out.append(f"inline DispatchResult parse_{disc_name}(const Json& raw) {{\n")
        out.append("    if (!raw.contains(\"_type\")) {\n")
        if disc.missing_type_rule_id:
            out.append(f"        return DispatchResult{{nullptr, RuleCatalog::make_problem({_cpp_lit(disc.missing_type_rule_id)}, \"\")}};\n")
        else:
            out.append("        std::map<std::string, std::string> ph0;\n")
            out.append("        ph0[\"schema-message\"] = \"missing _type\";\n")
            out.append(f"        return DispatchResult{{nullptr, RuleCatalog::make_problem({_cpp_lit(disc_name + '-0000')}, \"\", ph0)}};\n")
        out.append("    }\n")
        out.append("    const Json& tvj = raw.at(\"_type\");\n")
        out.append("    const bool tv_is_str = tvj.is_string();\n")
        out.append("    std::string tv = tv_is_str ? tvj.as<std::string>() : pyfmt::str(tvj);\n")
        out.append("    std::unique_ptr<SedBase> obj;\n")
        for i, (tc, br) in enumerate(disc.branches.items()):
            kw = "if" if i == 0 else "else if"
            out.append(f"    {kw} (tv_is_str && tv == {_cpp_lit(tc)}) obj = std::make_unique<{br.class_name}>();\n")
        out.append("    if (obj) {\n")
        out.append("        load_fields(obj.get(), raw);\n")
        out.append("        return DispatchResult{std::move(obj), std::nullopt};\n")
        out.append("    }\n")
        out.append("    std::smatch m;\n")
        out.append("    bool ns_match = tv_is_str && std::regex_match(tv, m, namespace_key_pattern());\n")
        known = ", ".join(_cpp_lit(b.namespace) for b in disc.branches.values() if b.namespace)
        out.append(f"    static const std::set<std::string> known = {{{known}}};\n")
        out.append("    if (ns_match && !known.count(m[1].str())) {\n")
        out.append(f"        return DispatchResult{{std::make_unique<{uname}>(tv, raw), std::nullopt}};\n")
        out.append("    }\n")
        out.append("    std::map<std::string, std::string> ph;\n")
        out.append("    ph[\"schema-message\"] = \"unrecognized _type \" + pyfmt::repr(tvj);\n")
        out.append(f"    return DispatchResult{{std::make_unique<{uname}>(tv, raw), "
                    f"RuleCatalog::make_problem({_cpp_lit(disc_name + '-0000')}, \"\", ph)}};\n")
        out.append("}\n\n")

    out.append("inline DispatchResult dispatch_parse(const std::string& disc_name, const Json& raw) {\n")
    for i, disc_name in enumerate(model.discriminators):
        kw = "if" if i == 0 else "else if"
        out.append(f"    {kw} (disc_name == {_cpp_lit(disc_name)}) return parse_{disc_name}(raw);\n")
    out.append("    throw ApiError(\"unknown discriminator \" + disc_name);\n}\n\n")

    # Covers an "array"-kind field's own item_class, a "dict"-kind field's
    # item_class when it has no _type dispatch of its own (SEDDocument.
    # styles -> Style, Loop.loopVariables -> LoopVariable, ...), and a
    # "ref-class"-kind field's item_class (the fixed target class a single
    # nested child constructs directly) - same construction need in all
    # three, just a different cardinality.
    item_classes = sorted({f.type.item_class for c in model.classes.values() for f in c.fields
                            if f.type.item_class and f.type.kind in ("array", "dict", "ref-class")})
    out.append("inline std::unique_ptr<SedBase> new_item_instance(const std::string& class_name) {\n")
    for i, cls_name in enumerate(item_classes):
        kw = "if" if i == 0 else "else if"
        out.append(f"    {kw} (class_name == {_cpp_lit(cls_name)}) return std::make_unique<{cls_name}>();\n")
    out.append("    throw ApiError(\"unknown item class \" + class_name);\n}\n\n")

    out.append('''inline void load_fields(SedBase* obj, const Json& raw) {
    if (!raw.is_object()) return;   // never throw for a malformed document
    if (raw.contains("name") && !raw.at("name").is_null()) obj->name_node_ = raw.at("name");
    if (raw.contains("description") && !raw.at("description").is_null()) obj->description_node_ = raw.at("description");
    if (raw.contains("_type")) obj->values_["_type"] = raw.at("_type");

    // The full OrRef family whose value is loaded via the generic
    // set_or_ref_value_node/set_or_ref_ref_node pair rather than a plain
    // obj->values_[...] assignment - see generator/emit_cpp.py's
    // _ORREF_KINDS_CPP (the same six kinds every generated model class's
    // own accessors handle).
    static const std::set<std::string> orref_kinds = {
        "StringOrRef", "NumberOrRef", "IntegerOrRef", "BooleanOrRef", "ArrayOrRef", "DictOrRef"};

    for (const auto& spec : obj->field_specs()) {
        if (!raw.contains(spec.name) || spec.kind == "dict" || spec.kind == "array"
                || spec.kind == "any-dict" || spec.kind == "ref-class"
                || spec.kind == "ref-discriminator") continue;
        const Json& v = raw.at(spec.name);
        if (orref_kinds.count(spec.kind)) {
            if (v.is_string() && is_reference(v.as<std::string>())) {
                obj->set_or_ref_ref_node(spec.name, v.as<std::string>());
            } else {
                obj->set_or_ref_value_node(spec.name, v);
            }
        } else {
            obj->values_[spec.name] = v;
        }
    }
    for (const auto& kv : obj->namespace_fields()) {
        for (const auto& spec : kv.second) {
            if (raw.contains(spec.name)) obj->values_[spec.name] = raw.at(spec.name);
        }
    }

    std::set<std::string> allowed = obj->allowed_keys();
    for (const auto& kv : raw.object_range()) {
        const std::string& key = kv.key();
        if (key == "_type" || key == "name" || key == "description") continue;
        if (allowed.count(key)) continue;
        std::smatch m;
        if (std::regex_match(key, m, namespace_key_pattern())) {
            std::string prefix = m[1].str(), ns_key = m[2].str();
            obj->set_namespace_attribute(prefix, ns_key, kv.value());
            if (obj->known_namespace_prefixes().count(prefix)) {
                std::string catchall = obj->namespace_catchall().count(prefix)
                        ? obj->namespace_catchall().at(prefix) : obj->own_catchall();
                std::map<std::string, std::string> ph;
                ph["schema-message"] = "Additional property '" + key + "' is not allowed.";
                obj->load_problems_.push_back(RuleCatalog::make_problem(catchall, "", ph));
            }
            continue;
        }
        std::map<std::string, std::string> ph;
        ph["schema-message"] = "Additional property '" + key + "' is not allowed.";
        obj->load_problems_.push_back(RuleCatalog::make_problem(obj->own_catchall(), "", ph));
    }

    for (const auto& spec : obj->field_specs()) {
        if (spec.kind == "dict" && raw.contains(spec.name)) {
            const Json& raw_value = raw.at(spec.name);
            if (!raw_value.is_object()) {
                std::string rid = spec.rule_id ? *spec.rule_id : spec.origin_catchall;
                std::map<std::string, std::string> ph;
                ph["attr"] = spec.name;
                ph["class"] = obj->class_name();
                ph["id"] = obj->own_id_for_message();
                ph["value"] = pyfmt::str(raw_value);
                obj->load_problems_.push_back(RuleCatalog::make_problem(rid, "/" + spec.name, ph));
                continue;
            }
            IdKeyedCollection& coll = obj->get_dict_collection(spec.name);
            // A dict-kind field is either _type-dispatched (item_discriminator
            // set, e.g. SEDDocument.tasks -> AbstractTask) or a plain
            // fixed-class dict with no _type dispatch at all (item_class set
            // instead, e.g. SEDDocument.styles -> Style, Loop.loopVariables
            // -> LoopVariable) - dereferencing spec.item_discriminator
            // unconditionally would be undefined behavior when it's
            // std::nullopt, so this mirrors the "array"-kind branch's own
            // new_item_instance fallback just below, and
            // generator/emit_python.py's _load_fields dict branch
            // (`dispatch = ... if spec.item_discriminator else None`), the
            // reference implementation this ports.
            for (const auto& item_kv : raw_value.object_range()) {
                const std::string& item_id = item_kv.key();
                const Json& item_raw = item_kv.value();
                if (!LeafValidation::is_sid(item_id)) {
                    std::string rid = spec.rule_id ? *spec.rule_id : spec.origin_catchall;
                    std::map<std::string, std::string> ph;
                    ph["attr"] = spec.name;
                    ph["class"] = obj->class_name();
                    ph["id"] = obj->own_id_for_message();
                    ph["value"] = item_id;
                    obj->load_problems_.push_back(RuleCatalog::make_problem(rid, "/" + spec.name, ph));
                }
                std::unique_ptr<SedBase> child;
                if (spec.item_discriminator) {
                    DispatchResult r = dispatch_parse(*spec.item_discriminator, item_raw);
                    if (r.problem) obj->load_problems_.push_back(*r.problem);
                    child = std::move(r.value);
                } else {
                    child = new_item_instance(*spec.item_class);
                    load_fields(child.get(), item_raw);
                }
                if (child) coll.add(item_id, std::move(child));
            }
        } else if (spec.kind == "array" && raw.contains(spec.name)) {
            const Json& raw_value = raw.at(spec.name);
            if (!raw_value.is_array()) {
                std::string rid = spec.rule_id ? *spec.rule_id : spec.origin_catchall;
                std::map<std::string, std::string> ph;
                ph["attr"] = spec.name;
                ph["class"] = obj->class_name();
                ph["id"] = obj->own_id_for_message();
                ph["value"] = pyfmt::str(raw_value);
                obj->load_problems_.push_back(RuleCatalog::make_problem(rid, "/" + spec.name, ph));
                continue;
            }
            ListCollection& coll = obj->get_list_collection(spec.name);
            for (const auto& item_raw : raw_value.array_range()) {
                std::unique_ptr<SedBase> child = new_item_instance(*spec.item_class);
                load_fields(child.get(), item_raw);
                coll.add(std::move(child));
            }
        } else if (spec.kind == "any-dict" && raw.contains(spec.name)) {
            // Same ID-keyed-collection shape as "dict" just above, but every
            // value is stored as-is - a plain Json, never
            // constructed as a class instance (see this module's
            // _collection_accessors_cpp any-dict branch and
            // generator/emit_python.py's _load_fields any-dict branch, the
            // reference implementation this mirrors).
            const Json& raw_value = raw.at(spec.name);
            if (!raw_value.is_object()) {
                std::string rid = spec.rule_id ? *spec.rule_id : spec.origin_catchall;
                std::map<std::string, std::string> ph;
                ph["attr"] = spec.name;
                ph["class"] = obj->class_name();
                ph["id"] = obj->own_id_for_message();
                ph["value"] = pyfmt::str(raw_value);
                obj->load_problems_.push_back(RuleCatalog::make_problem(rid, "/" + spec.name, ph));
                continue;
            }
            AnyDictCollection& coll = obj->get_any_dict_collection(spec.name);
            for (const auto& item_kv : raw_value.object_range()) {
                const std::string& item_id = item_kv.key();
                if (!LeafValidation::is_sid(item_id)) {
                    std::string rid = spec.rule_id ? *spec.rule_id : spec.origin_catchall;
                    std::map<std::string, std::string> ph;
                    ph["attr"] = spec.name;
                    ph["class"] = obj->class_name();
                    ph["id"] = obj->own_id_for_message();
                    ph["value"] = item_id;
                    obj->load_problems_.push_back(RuleCatalog::make_problem(rid, "/" + spec.name, ph));
                }
                coll.add(item_id, item_kv.value());
            }
        } else if ((spec.kind == "ref-class" || spec.kind == "ref-discriminator") && raw.contains(spec.name)) {
            // A single nested SedBase-derived child (see this module's
            // _child_accessors_cpp docstring) - "ref-class" constructs a
            // fixed target class directly; "ref-discriminator" dispatches
            // on the raw JSON's own _type via the matching parse_*
            // function, same as a dict-kind field's own discriminated
            // items above. Mirrors generator/emit_python.py's _load_fields
            // ref-class/ref-discriminator branch.
            const Json& raw_value = raw.at(spec.name);
            if (!raw_value.is_object()) {
                std::string rid = spec.rule_id ? *spec.rule_id : spec.origin_catchall;
                std::map<std::string, std::string> ph;
                ph["attr"] = spec.name;
                ph["class"] = obj->class_name();
                ph["id"] = obj->own_id_for_message();
                ph["value"] = pyfmt::str(raw_value);
                obj->load_problems_.push_back(RuleCatalog::make_problem(rid, "/" + spec.name, ph));
                continue;
            }
            std::unique_ptr<SedBase> child;
            if (spec.kind == "ref-discriminator") {
                DispatchResult r = dispatch_parse(*spec.item_discriminator, raw_value);
                if (r.problem) obj->load_problems_.push_back(*r.problem);
                child = std::move(r.value);
            } else {
                child = new_item_instance(*spec.item_class);
                load_fields(child.get(), raw_value);
            }
            if (child) obj->set_child_field(spec.name, std::move(child));
        }
    }
}

''')
    out.append(f"}}  // namespace {NS}\n")
    return "".join(out)


def emit_direct_only_hpp(model: SpecModel) -> str:
    """rule_id -> factory, for every generated class whose own _type-const
    rule can only be exercised by validating that class directly - not
    embedded through a parent's discriminated dict/array field, where a
    _type mismatch is caught by the parent's own dispatch first (see
    Design.md's Testing section). C++ has no runtime reflection (unlike
    Python's inspect.getmembers() or Java's classloader-based scan - see
    templates/python/tests/test_fixtures.py and templates/java/tests/
    FixtureTest.java), so this table is built here, at generate time, from
    the same per-class type_rule_id() metadata those two discover at their
    own run time - every class in model.generatable_classes() with a
    non-empty type_rule_id, which is exactly the set with a default
    constructor available (the only other classes, the discriminator
    Unknown* holders, take constructor arguments and have no type_rule_id
    to begin with - see emit_dispatch_hpp's Unknown* handling). This keeps
    templates/cpp/tests/FixtureTest.cpp itself free of any spec-specific
    class or rule-ID knowledge, the same as the other two targets.
    GENERATED - do not hand-edit; regenerate via generator/generate.py."""
    out = [f'''// Generated direct-only-class registry (see this file's own generator,
// generator/emit_cpp.py's emit_direct_only_hpp, for what this is and why
// it exists). GENERATED - do not hand-edit; regenerate via
// generator/generate.py.
#pragma once

#include "GeneratedModel.hpp"

#include <functional>
#include <map>
#include <memory>
#include <string>

namespace {NS} {{

inline const std::map<std::string, std::function<std::unique_ptr<SedBase>()>>& direct_only_classes() {{
    static const std::map<std::string, std::function<std::unique_ptr<SedBase>()>> m = {{
''']
    for name in model.generatable_classes():
        rid = model.classes[name].type_rule_id
        if rid:
            out.append(f"        {{{_cpp_lit(rid)}, [] {{ return std::unique_ptr<SedBase>(std::make_unique<{name}>()); }}}},\n")
    out.append("    };\n    return m;\n}\n\n")
    out.append(f"}}  // namespace {NS}\n")
    return "".join(out)


