def _math_ast_hpp(ns: str) -> str:
    """MathAst.hpp - C++ port of emit_python.py's math_ast.py (the
    RUNTIME-embedded ASTNode/_Builder/parse() trio) and its Java analog,
    emit_java.py's _math_ast_java() (see that function's docstring for the
    shared rationale: trimmed to what MathRules.hpp's Types-0002/-0003/-
    0004 checks actually walk, no to_string()/_render). Builds on the
    ANTLR-generated mathLexer/mathParser/mathBaseVisitor in the
    `{ns}::antlr` namespace (see antlr_tool.generate_cpp_math_parser,
    called from emit_cpp_package) - same math.g4 grammar as the other two
    targets, so this desugaring (relational-chain / logical-run flattening,
    '%' -> rem(), unary '!' -> not()) mirrors _Builder/Builder in the
    Python/Java emitters exactly; see either one's comments for the
    semantics. Unlike Java's visitor (parameterized on the AST node type),
    ANTLR's C++ visitor always returns std::any, so every visit method here
    wraps/unwraps a std::shared_ptr<MathNode> through it (visit_node()).
    GENERATED - do not hand-edit; regenerate via generator/generate.py."""
