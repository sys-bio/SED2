def _normalize_arity_cpp(raw) -> tuple:
    """Same two-shape contract as emit_python.py's _normalize_arity /
    emit_java.py's _normalize_arity_java (kept as an independent copy -
    see this module's docstring on the three emitters staying self-
    contained)."""
    if isinstance(raw, bool):
        raise ValueError(f"unrecognized arity shape: {raw!r}")
    if isinstance(raw, int):
        return ("set", [raw])
    if isinstance(raw, list):
        return ("set", sorted(set(raw)))
    if isinstance(raw, dict):
        return ("range", raw.get("min", 0), raw.get("max"))
    raise ValueError(f"unrecognized arity shape: {raw!r}")


